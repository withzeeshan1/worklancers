// Writes the security headers from security-headers.js into every hosting config,
// so Apache, Netlify and Vercel always send exactly the same headers. Runs before each build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';
import { securityHeadersFor } from '../security-headers.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Site settings from client/.env and the hosting's environment variables (same as the build uses).
const env = loadEnv('production', root, 'VITE_');
const entries = Object.entries(securityHeadersFor(env));
const write = (rel, text) => fs.writeFileSync(path.join(root, rel), text);

// ---- Netlify: public/_headers
write('public/_headers', `# GENERATED by scripts/sync-security-headers.mjs from security-headers.js. Do not edit by hand.\n/*\n${entries.map(([k, v]) => `  ${k}: ${v}`).join('\n')}\n`);

// ---- Vercel: vercel.json
write('vercel.json', `${JSON.stringify({
  cleanUrls: true,
  trailingSlash: false,
  headers: [{ source: '/(.*)', headers: entries.map(([key, value]) => ({ key, value })) }],
}, null, 2)}\n`);

// ---- Apache / cPanel / MAMP: public/.htaccess
const apacheHeaders = entries.map(([k, v]) => (k === 'Strict-Transport-Security'
  ? `  # HTTPS only\n  Header always set ${k} "${v}" "expr=%{HTTPS} == 'on'"`
  : `  Header always set ${k} "${v}"`)).join('\n');

write('public/.htaccess', `# GENERATED by scripts/sync-security-headers.mjs. Edit security-headers.js or that script instead.
# Apache / cPanel / MAMP. Every page is a pre-rendered .html file (see scripts/prerender.mjs).

# ---------------- Security ----------------
# Hide the server version and never list folder contents.
ServerSignature Off
Options -Indexes

# Block sensitive files if they are ever uploaded by mistake (backups, logs, source maps, configs).
<FilesMatch "\\.(map|bak|old|orig|swp|sql|log|ini|sh|env|config|lock|md|yml|yaml)$|^(package(-lock)?\\.json|composer\\.(json|lock)|vercel\\.json)$">
  <IfModule mod_authz_core.c>
    Require all denied
  </IfModule>
</FilesMatch>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  # One address for search engines: www.example.com -> https://example.com (straight to HTTPS, one hop).
  # Matches the canonical links, which use VITE_SITE_URL without "www".
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L]
  # Always use HTTPS (skipped on localhost; also respects proxies such as Cloudflare).
  RewriteCond %{HTTPS} off
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteCond %{HTTP_HOST} !^(localhost|127\\.0\\.0\\.1)(:[0-9]+)?$ [NC]
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
  # A static site only needs GET/HEAD/OPTIONS; refuse everything else (PUT, DELETE, TRACE...).
  RewriteCond %{REQUEST_METHOD} !^(GET|HEAD|OPTIONS)$
  RewriteRule ^ - [R=405,L]
  # Block hidden files and folders such as .git or .env (but allow /.well-known/).
  RewriteRule (^|/)\\.(?!well-known/) - [F,L]
</IfModule>

<IfModule mod_headers.c>
${apacheHeaders}
  Header unset X-Powered-By
</IfModule>

# ---------------- Pages ----------------
DirectoryIndex index.html
# Folders like /services/ also hold sub-pages; don't redirect /services to /services/.
DirectorySlash Off

<IfModule mod_rewrite.c>
  # Redirect old trailing-slash URLs to the canonical address (e.g. /services/ -> /services)
  RewriteCond %{REQUEST_URI} !^/$
  RewriteCond %{REQUEST_URI} !^/\\.well-known/
  RewriteRule ^(.+)/$ /$1 [R=301,L]
  # /services -> services.html, /services/web-development -> services/web-development.html
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME}.html -f
  RewriteRule ^(.+)$ $1.html [L]
</IfModule>

# Unknown addresses get a real 404 status (good for SEO) with the site's 404 page.
ErrorDocument 404 /404.html

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml application/xml text/plain
</IfModule>

# Cache hashed build assets and images for a year; always re-check the HTML.
<IfModule mod_headers.c>
  <FilesMatch "\\.(js|css|svg|png|jpg|jpeg|webp|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`);

console.log(`Security headers synced (${entries.length} headers${env.VITE_CF_ANALYTICS_TOKEN ? ', Cloudflare analytics allowed' : ''}) -> public/.htaccess, public/_headers, vercel.json`);
